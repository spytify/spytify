// Command gendocs writes the v2 settings page of the GitHub Pages site and
// the protocol section of its Advanced page from the settings table and the
// messaging contract, so the documentation cannot drift from the code:
//
//	go run ./internal/tools/gendocs -out <gh-pages checkout>
//
// It writes v2/settings.md and _includes/v2-protocol.md, which
// v2/advanced.md includes.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"

	"github.com/spytify/spytify/internal/settings"
	"github.com/spytify/spytify/pkg/proto"
)

const generated = "<!-- Generated by `go run ./internal/tools/gendocs` from the code; edit the code, not this page. -->\n\n"

func main() {
	out := flag.String("out", ".", "the site's root folder")
	flag.Parse()
	for name, body := range map[string]string{"v2/settings.md": settingsPage(), "_includes/v2-protocol.md": protocolSection()} {
		path := filepath.Join(*out, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

func frontMatter(title string) string {
	return "---\nlayout: page\ntitle: " + title + "\nversion: v2\n---\n\n" + generated
}

func settingsPage() string {
	var b strings.Builder
	b.WriteString(frontMatter("Settings"))
	b.WriteString("Every setting is in `config.toml`, which the recorder validates. Change them in the app's Settings, where the advanced ones are folded under each section, or with `spytify-cli set key=value`; `spytify-cli get` lists them.\n")
	var groups []string
	seen := map[string]bool{}
	for _, d := range settings.Table {
		if !seen[d.Group] {
			seen[d.Group] = true
			groups = append(groups, d.Group)
		}
	}
	for _, g := range groups {
		fmt.Fprintf(&b, "\n### %s\n", g)
		for _, advanced := range []bool{false, true} {
			var rows []settings.Def
			for _, d := range settings.Table {
				if d.Group == g && d.Advanced == advanced {
					rows = append(rows, d)
				}
			}
			if len(rows) == 0 {
				continue
			}
			if advanced {
				b.WriteString("\nAdvanced:\n")
			}
			b.WriteString("\n| Setting | Key | Values | Default |\n| --- | --- | --- | --- |\n")
			for _, d := range rows {
				fmt.Fprintf(&b, "| %s | `%s` | %s | %s |\n", cell(d.Label), d.Key, cell(values(d)), cell(defaultOf(d)))
			}
		}
	}
	b.WriteString("\nThe recorded application is chosen with environment variables, not in `config.toml`: see [Configuration](advanced.html#configuration).\n")
	return b.String()
}

func values(d settings.Def) string {
	switch d.Kind {
	case settings.KindBool:
		return "on, off"
	case settings.KindEnum:
		return strings.Join(d.Enum, ", ")
	case settings.KindIntEnum:
		var s []string
		for _, n := range d.Ints {
			s = append(s, fmt.Sprint(n))
		}
		return strings.Join(s, ", ")
	case settings.KindInt, settings.KindFloat:
		if d.Ranged {
			return number(d.Min) + " to " + number(d.Max)
		}
		return "a number"
	case settings.KindPath:
		return "a folder: absolute, or starting with ~/"
	case settings.KindDuration:
		return "a duration such as 90m or 2h"
	case settings.KindTemplate:
		return d.Note
	}
	return "text"
}

func number(f float64) string { return strconv.FormatFloat(f, 'f', -1, 64) }

func defaultOf(d settings.Def) string {
	switch v := d.Default.(type) {
	case bool:
		if v {
			return "on"
		}
		return "off"
	case string:
		if v == "" {
			return "none"
		}
		return "`" + v + "`"
	}
	return fmt.Sprint(d.Default)
}

// cell keeps a value from breaking the Markdown table.
func cell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

// protocolSection is the Protocol section of the Advanced page, without
// its heading.
func protocolSection() string {
	var b strings.Builder
	b.WriteString(generated)
	b.WriteString(fmt.Sprintf("Clients speak newline-delimited JSON-RPC 2.0, protocol version %d, on the recorder's socket, and on TCP with `spytifyd --listen 127.0.0.1:7811`. Actions are requests; events are notifications sent to every client. Go clients import `github.com/spytify/spytify/pkg/proto`; the same contract is in [`pkg/proto/schema.json`](https://github.com/spytify/spytify/blob/master/pkg/proto/schema.json).\n\n", proto.Protocol))
	b.WriteString("```json\n{\"jsonrpc\":\"2.0\",\"id\":7,\"method\":\"settings.set\",\"params\":{\"values\":{\"encode.format\":\"flac\"}}}\n{\"jsonrpc\":\"2.0\",\"id\":7,\"result\":{\"applied\":[\"encode.format\"],\"rejected\":{}}}\n{\"jsonrpc\":\"2.0\",\"method\":\"settings.changed\",\"params\":{\"values\":{\"encode.format\":\"flac\"}}}\n```\n")
	types := map[string]reflect.Type{}
	b.WriteString("\n### Actions\n\n| Method | Params | Result | Does |\n| --- | --- | --- | --- |\n")
	for _, m := range proto.Methods {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", m.Name, typeCell(m.Params, types), typeCell(m.Result, types), cell(m.Doc))
	}
	b.WriteString("\n### Events\n\n| Event | Payload | Sent |\n| --- | --- | --- |\n")
	for _, e := range proto.Events {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", e.Name, typeCell(e.Payload, types), cell(e.Doc))
	}
	b.WriteString("\n### Types\n")
	for done := map[string]bool{}; len(done) < len(types); {
		names := make([]string, 0, len(types))
		for n := range types {
			if !done[n] {
				names = append(names, n)
			}
		}
		sort.Strings(names)
		for _, n := range names {
			done[n] = true
			t := types[n]
			fmt.Fprintf(&b, "\n#### %s\n\n", n)
			fields := structFields(t, types)
			if len(fields) == 0 {
				b.WriteString("An empty object.\n")
				continue
			}
			b.WriteString("| Field | Type |\n| --- | --- |\n")
			for _, f := range fields {
				fmt.Fprintf(&b, "| `%s` | %s |\n", f[0], f[1])
			}
		}
	}
	return b.String()
}

func typeCell(v any, types map[string]reflect.Type) string {
	if v == nil {
		return "none"
	}
	return typeName(reflect.TypeOf(v), types)
}

// typeName names t for a reader, and collects the structs it uses.
func typeName(t reflect.Type, types map[string]reflect.Type) string {
	if t == reflect.TypeOf(json.RawMessage{}) {
		return "any JSON"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return typeName(t.Elem(), types)
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int32, reflect.Int64:
		return "integer"
	case reflect.Float64:
		return "number"
	case reflect.String:
		return "string"
	case reflect.Slice:
		return "array of " + typeName(t.Elem(), types)
	case reflect.Map:
		return "object of " + typeName(t.Elem(), types)
	case reflect.Struct:
		types[t.Name()] = t
		return "[" + t.Name() + "](#" + strings.ToLower(t.Name()) + ")"
	}
	return "any"
}

func structFields(t reflect.Type, types map[string]reflect.Type) [][2]string {
	var out [][2]string
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if f.Anonymous && f.Type.Kind() == reflect.Struct {
			out = append(out, structFields(f.Type, types)...)
			continue
		}
		tag := f.Tag.Get("json")
		if !f.IsExported() || tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if name == "" {
			name = f.Name
		}
		kind := typeName(f.Type, types)
		if strings.Contains(opts, "omitempty") {
			kind += ", optional"
		}
		out = append(out, [2]string{name, kind})
	}
	return out
}
