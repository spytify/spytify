// Command genkeys writes keys_gen.go in internal/settings: a settings.Key
// for each row of the settings table, named from its key, so that code
// names a setting with an identifier the compiler checks rather than with a
// string. A setting that takes one of a list also gets a type, a constant
// for each value and a getter on Values. It runs through go generate in
// internal/settings.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"strings"

	"github.com/spytify/spytify/internal/settings"
	"github.com/spytify/spytify/internal/ui/lang"
)

func main() {
	out := flag.String("o", "keys_gen.go", "output file")
	flag.Parse()
	src, err := render(settings.Table)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// render is keys_gen.go for table.
func render(table []settings.Def) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ../tools/genkeys from Table; DO NOT EDIT.\n\npackage settings\n\n")
	b.WriteString("// The settings, in Table's order.\nvar (\n")
	seen := map[string]string{}
	for i, d := range table {
		name := identifier(d.Key)
		if !token.IsIdentifier(name) {
			return nil, fmt.Errorf("%s makes no Go name: keys are made of lower-case words, dots and underscores", d.Key)
		}
		if other, ok := seen[name]; ok {
			return nil, fmt.Errorf("%s and %s are both named %s", other, d.Key, name)
		}
		seen[name] = d.Key
		if i > 0 && d.Group != table[i-1].Group {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "\t// %s is %s, %q in Settings.\n\t%s = Key{%q}\n", name, d.Key, lang.SettingTexts[d.Key].Label, name, d.Key)
	}
	b.WriteString(")\n")
	for _, d := range table {
		if d.Kind != settings.KindEnum {
			continue
		}
		typ := identifier(d.Key[strings.LastIndex(d.Key, ".")+1:])
		if other, ok := seen[typ]; ok {
			return nil, fmt.Errorf("%s and %s are both named %s", other, d.Key, typ)
		}
		seen[typ] = d.Key
		fmt.Fprintf(&b, "\n// %s is a value of %s.\ntype %s string\n\n// The values of %s, as Settings names them.\nconst (\n", typ, d.Key, typ, d.Key)
		choices := lang.SettingTexts[d.Key].Choices
		for i, v := range d.Enum {
			fmt.Fprintf(&b, "\t%s %s = %q", typ+identifier(v), typ, v)
			if i < len(choices) {
				fmt.Fprintf(&b, " // %s", choices[i])
			}
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, ")\n\n// %s is the value of %s.\nfunc (v Values) %s() %s { return %s(v.String(%s)) }\n", typ, d.Key, typ, typ, typ, identifier(d.Key))
	}
	return format.Source(b.Bytes())
}

// identifier is the key's Go name: recorder.trim_silence is
// RecorderTrimSilence. An enum's value is named the same way after its
// type: artist/album is GroupByArtistAlbum.
func identifier(key string) string {
	var b strings.Builder
	for _, word := range strings.FieldsFunc(key, func(r rune) bool { return r == '.' || r == '_' || r == '/' }) {
		b.WriteString(strings.ToUpper(word[:1]) + word[1:])
	}
	return b.String()
}
